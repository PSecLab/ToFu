#!/usr/bin/env python3
"""Executed-repo set: every repo where ToFu executed >= 1 tool call in a campaign
that contributes to the paper headline. Writes executed_repos.txt (the dataset
denominator) and executed_succ_repos.txt (the subset with >= 1 successful call).

Why this set: every headline bug comes from a tool that executed (introspection
tracers fire on calls that error, e.g. SSRF dial-then-fail), so "executed" is the
set the headline is drawn from. The older ablation_251_repos.txt is narrower: >= 1
*successful* call in the 60 s sandboxed sweeps only. It omits repos whose headline
bugs came from the 24 h deep run or from executed-but-errored tools.

Sources = the headline campaigns (findings/union_20260926/analyze_union.py):
  corpus_sbx_20260926, recover_pc_20260926   60 s sandboxed sweeps
  repo24_20260926 (repo24, repo24-b)         24 h deep run, sandboxed
  baselines/tofu_runs_e2_20260922            60 s (introspection-on-errored source)
Run from the repo root: python3 Benchmarks/extraction/build_executed_set.py
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
F = lambda *p: os.path.join(ROOT, "findings", *p)
SRC = [F("corpus_sbx_20260926", "runs.gpt41-corpus-sbx.jsonl"),
       F("recover_pc_20260926", "runs.gpt41-recover-pc.jsonl"),
       F("repo24_20260926", "runs.repo24.jsonl"),
       F("repo24_20260926", "runs.repo24-b.jsonl"),
       F("baselines", "tofu_runs_e2_20260922.jsonl")]

attempted, executed, succeeded = set(), set(), set()
for p in SRC:
    for line in open(p):
        if not line.strip():
            continue
        r = json.loads(line)
        repo = r.get("repo")
        attempted.add(repo)
        if (r.get("n_exec") or 0) > 0:
            executed.add(repo)
        if (r.get("n_exec_success") or 0) > 0:
            succeeded.add(repo)

out = os.path.join(ROOT, "Benchmarks", "extraction")
hdr = "# generated by build_executed_set.py -- do not edit by hand\n"
open(os.path.join(out, "executed_repos.txt"), "w").write(hdr + "\n".join(sorted(executed)) + "\n")
open(os.path.join(out, "executed_succ_repos.txt"), "w").write(hdr + "\n".join(sorted(succeeded)) + "\n")
print(f"attempted {len(attempted)} | executed >=1 call {len(executed)} | >=1 successful call {len(succeeded)}")
