#!/usr/bin/env python3
"""Head-to-head set = the 273 repos where ToFu saw >= 1 successful tool call in a
headline campaign (executed_succ_repos.txt, from build_executed_set.py). Writes:

  h2h_273_repos.txt          the 273 (static baselines + ToFu + Sonnet-5 are scored on these)
  h2h_273_dynamic_repos.txt  273 minus set_e2_unsafe_repos.txt (host-control servers that
                             Viper / ToolFuzz must not drive: tmux, shells, frida, simulators)
  viper_273_todo_repos.txt   dynamic set minus the 251 Viper already ran in c251
  tofu_exec_index_273.jsonl  ToFu-executed tools for ToolFuzz --executable-only
                             (TOOLFUZZ_TOFU_INDEX): every (repo, tool) with >= 1 successful
                             exec in ANY headline campaign. The PC's tofu_sbx_index.jsonl only
                             has the sandboxed sweeps, so it misses the 22 repos whose only
                             successful calls are in the 09-22 run.
Run from the repo root: python3 Benchmarks/extraction/build_h2h_273.py
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
X = lambda *p: os.path.join(ROOT, "Benchmarks", "extraction", *p)
F = lambda *p: os.path.join(ROOT, "findings", *p)
rd = lambda p: {l.strip() for l in open(p) if l.strip() and not l.startswith("#")}

S273 = rd(X("executed_succ_repos.txt"))
R251 = rd(X("ablation_251_repos.txt"))
UNSAFE = {x.strip() for x in open(X("set_e2_unsafe_repos.txt")).read().replace("\n", ",").split(",") if x.strip()}
assert R251 <= S273, "251 must be a subset of the 273"

SRC = [F("corpus_sbx_20260926", "runs.gpt41-corpus-sbx.jsonl"),
       F("recover_pc_20260926", "runs.gpt41-recover-pc.jsonl"),
       F("repo24_20260926", "runs.repo24.jsonl"),
       F("repo24_20260926", "runs.repo24-b.jsonl"),
       F("baselines", "tofu_runs_e2_20260922.jsonl")]
exe = {}
for p in SRC:
    for line in open(p):
        if not line.strip():
            continue
        r = json.loads(line)
        if r.get("repo") in S273 and (r.get("n_exec_success") or 0) > 0:
            exe[(r["repo"], r["tool"])] = r.get("config")

dyn = S273 - UNSAFE
todo = dyn - R251
hdr = "# generated by build_h2h_273.py -- do not edit by hand\n"
w = lambda name, s: open(X(name), "w").write(hdr + "\n".join(sorted(s)) + "\n")
w("h2h_273_repos.txt", S273)
w("h2h_273_dynamic_repos.txt", dyn)
w("viper_273_todo_repos.txt", todo)
with open(X("tofu_exec_index_273.jsonl"), "w") as f:
    for (repo, tool), cfg in sorted(exe.items()):
        if repo in dyn:
            f.write(json.dumps({"repo": repo, "tool": tool, "config": cfg, "ok": True, "executable": "yes"}) + "\n")
print(f"h2h 273 | dynamic {len(dyn)} (unsafe excluded: {sorted(S273 & UNSAFE)}) | "
      f"viper todo {len(todo)} | toolfuzz executed tools {sum(1 for k in exe if k[0] in dyn)} "
      f"in {len({k[0] for k in exe if k[0] in dyn})} repos")
