#!/usr/bin/env python3
"""Viper-MCP over the H2H-273 dynamic set (266 repos; campaign tag c251, 2026-09-28) vs ToFu's 508.
Regenerates findings/viper_c251_20260928/{REPORT.md,per_repo.json}. Run from the repo root:
  python3 findings/viper_c251_20260928/analyze_viper_c251.py

Inputs (all committed here):
  runs.c251.jsonl          Viper index, one row per repo (VM eval/state/viper_runs.c251.jsonl)
  confirmed_verdicts.json  every Viper hit-judge verdict with sink_reached && effect_success,
                           with Viper's own judge text (from fuzz_results/*/triggered_vulnerability_prompts.json)
  llm_ledger_summary.json  measured LLM traffic from the record/replay cache ledger
ToFu = the 508 paper headline: findings/union_20260926/analyze_union.py's U minus the backend-dial
       SSRF set, both as computed by findings/baselines/h2h_tofu_vs_viper_20260926.py.
"""
import json, os, runpy, collections, contextlib, io
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
P = lambda *p: os.path.join(HERE, *p)

X = lambda f: [l.strip() for l in open(os.path.join(ROOT, "Benchmarks", "extraction", f)) if l.strip() and not l.startswith("#")]
REPOS = X("h2h_273_dynamic_repos.txt")        # 273 minus the unsafe host-control servers (build_h2h_273.py)
R273, R251 = set(X("h2h_273_repos.txt")), set(X("ablation_251_repos.txt"))
EXCL = sorted(R273 - set(REPOS))              # the 7 Viper/ToolFuzz must not drive
last = {}
for l in open(P("runs.c251.jsonl")):
    if l.strip():
        r = json.loads(l); last[r["repo"]] = r
verdicts = json.load(open(P("confirmed_verdicts.json")))
ledger = json.load(open(P("llm_ledger_summary.json")))

cwd = os.getcwd(); os.chdir(ROOT)
with contextlib.redirect_stdout(io.StringIO()):            # side effect: rewrites the 09-26 H2H files identically
    g = runpy.run_path(os.path.join(ROOT, "findings", "baselines", "h2h_tofu_vs_viper_20260926.py"))
os.chdir(cwd)
TOFU = g["U"] - g["backend_dial"]
assert len(TOFU) == 508, f"ToFu set is {len(TOFU)}, expected the 508 headline"
tofu = collections.defaultdict(set)
for repo, tool, cls in TOFU:
    tofu[repo].add((tool, cls))
recover21 = {r["repo"] for r in map(json.loads, open(os.path.join(ROOT, "findings", "recover_pc_20260926", "runs.gpt41-recover-pc.jsonl")))
             if (r.get("n_exec_success") or 0) > 0} & set(REPOS)

vc = collections.defaultdict(list)
for v in verdicts:
    vc[v["repo"]].append(v)

rows = []
for repo in REPOS:
    r = last.get(repo, {})
    chains = sorted({v["chain"] for v in vc.get(repo, [])})
    ctools = {c.split("->")[0].strip() for c in chains}
    t = tofu.get(repo, set())
    rows.append(dict(
        repo=repo, lang=r.get("lang"), viper_ok=bool(r.get("ok")), viper_error=(r.get("error") or "")[:80] or None,
        reused_run=bool(r.get("reused_from")), recover_pc=repo in recover21,
        hook=bool(r.get("hook_injected")), n_hook_inits=r.get("n_hook_inits", 0),
        v_static=r.get("n_static") or 0, v_sink=r.get("n_sink_events") or 0,
        v_confirmed=len(chains), v_verdicts=len(vc.get(repo, [])), v_chains=chains,
        tofu=len(t), tofu_classes=sorted({c for _, c in t}),
        tofu_same_tool=sorted({f"{tl}:{c}" for tl, c in t if tl in ctools}),
        seconds=r.get("seconds")))
json.dump(rows, open(P("per_repo.json"), "w"), indent=1)

ok = [x for x in rows if x["viper_ok"]]
n = lambda f, s=rows: sum(1 for x in s if f(x))
V = lambda x: x["v_static"] > 0 or x["v_sink"] > 0 or x["v_confirmed"] > 0
conf = [x for x in rows if x["v_confirmed"]]
LT = ledger["total"]; pt, ct = LT["prompt_tokens"], LT["completion_tokens"]
N = len(REPOS); s251 = [x for x in rows if x["repo"] in R251]
md = [
 f"# Viper-MCP over the H2H-273 dynamic set ({N} repos, campaign tag c251, 2026-09-28)", "",
 "Regenerated by `analyze_viper_c251.py` from the committed files in this directory.",
 f"**Set:** `Benchmarks/extraction/h2h_273_dynamic_repos.txt` ({N}) = the H2H-273 (repos where ToFu saw >= 1",
 "successful tool call in a headline campaign; `build_h2h_273.py`) minus the 7 unsafe host-control servers",
 "Viper must not drive: " + ", ".join(EXCL) + ".",
 f"**ToFu** = the 508 paper headline (RESULTS_SUMMARY §1a): {sum(len(tofu.get(r, ())) for r in R273)} of the 508 lie on the 273, "
 f"{sum(len(tofu.get(r, ())) for r in REPOS)} on these {N}.",
 "**Viper protocol:** gpt-4.1, temperature 0 (Viper's default is 0.7 -- a stated deviation), 10 rounds,",
 "1800 s/server, CodeQL 2.27.0, bubblewrap sandbox, Monika VM. Counts are Viper's own outputs:",
 "static = Phase I CodeQL taint flows (`codeql_output/*/report.json`); sink hits = Phase II hook",
 "observations excl. `hook_init`; **confirmed = distinct call chains with a Viper hit-judge verdict",
 "`sink_reached && effect_success`** (`fuzz_results/*/triggered_vulnerability_prompts.json`).", "",
 "> Units differ: ToFu bugs are runtime silent-bug candidates (distinct repo×tool×class); Viper-confirmed",
 "> is a judged exploit per call chain. Compare at repo / tool level; never add them.", "",
 "## Run health",
 f"- {n(lambda x: x['lang'] is not None)}/{N} repos have a Viper result; **{len(ok)} ok**, {len(rows) - len(ok)} failed "
 "(" + ", ".join(x["repo"] + " (" + str(x["viper_error"]) + ")" for x in rows if not x["viper_ok"]) + ").",
 f"- Hook proof (Viper's runtime hook provably loaded) on **{n(lambda x: x['hook'], ok)}/{len(ok)}** ok runs.",
 f"- {n(lambda x: x['reused_run'])} repos reuse an earlier valid node run (09-13/09-20, same protocol, hook proven);",
 f"  {len(rows) - n(lambda x: x['reused_run'])} ran fresh on 2026-09-28 (225 for the 251, then 12 for the 273 extension).",
 f"  The 21 PC-recovered repos all ran on the VM ({n(lambda x: x['recover_pc'] and x['viper_ok'])}/21 ok).",
 f"- LLM traffic (fresh runs only, measured): {LT['calls']:,} calls, {LT['replayed_from_cache']:,} replayed from",
 f"  cache, {LT['upstream']:,} upstream "
 f"({sum(int(w['upstream_status'].get('400', 0)) for w in ledger['windows'])} returned HTTP 400); "
 f"{pt:,} prompt / {ct:,} completion tokens (gpt-4.1). Per window in `llm_ledger_summary.json`.",
 f"  At gpt-4.1 list price ($2/M in, $8/M out -- not verified against the invoice) ≈ ${pt * 2e-6 + ct * 8e-6:,.0f}.", "",
 "## Headline",
 f"| | repos (of {N}) | count |", "|---|---|---|",
 f"| **ToFu** (508 headline) | **{n(lambda x: x['tofu'] > 0)}** | {sum(x['tofu'] for x in rows)} bugs |",
 f"| Viper static (Phase I) | {n(lambda x: x['v_static'] > 0)} | {sum(x['v_static'] for x in rows)} taint flows |",
 f"| Viper runtime sink hits (Phase II) | {n(lambda x: x['v_sink'] > 0)} | observations, not findings |",
 f"| **Viper confirmed** | **{len(conf)}** | {sum(x['v_confirmed'] for x in rows)} distinct chains "
 f"({sum(x['v_verdicts'] for x in rows)} verdicts) |", "",
 f"On the 251 subset (the earlier c251 scope): ToFu {n(lambda x: x['tofu'] > 0, s251)} repos, Viper static "
 f"{n(lambda x: x['v_static'] > 0, s251)}, sink {n(lambda x: x['v_sink'] > 0, s251)}, confirmed {n(lambda x: x['v_confirmed'] > 0, s251)}.",
 f"The 7 excluded unsafe repos carry {sum(len(tofu.get(r, ())) for r in EXCL)} ToFu bugs "
 f"({', '.join(f'{r} {len(tofu[r])}' for r in EXCL if tofu.get(r)) or 'none'}); Viper was not run on them by design.", "",
 "Repo-level overlap:",
 f"- ToFu ∩ Viper-static {n(lambda x: x['tofu'] and x['v_static'])}; ToFu-only (vs static) "
 f"{n(lambda x: x['tofu'] and not x['v_static'])}; Viper-static-only {n(lambda x: not x['tofu'] and x['v_static'])}.",
 f"- ToFu ∩ Viper-any-signal {n(lambda x: x['tofu'] and V(x))}; ToFu-only {n(lambda x: x['tofu'] and not V(x))}; "
 f"Viper-any-only {n(lambda x: not x['tofu'] and V(x))}.",
 f"- ToFu ∩ Viper-confirmed {n(lambda x: x['tofu'] and x['v_confirmed'])}; **Viper-confirmed where ToFu reports 0: "
 f"{n(lambda x: not x['tofu'] and x['v_confirmed'])}**.", "",
 "## Viper's confirmed bugs vs ToFu",
 "Class/assessment columns read Viper's own hit-judge text (in `confirmed_verdicts.json`); **none is hand-verified**.",
 "", "| repo | Viper chain (verdicts) | ToFu on this repo | ToFu on the same tool |", "|---|---|---|---|",
]
for x in sorted(conf, key=lambda x: (x["tofu"] > 0, x["repo"].lower())):
    md.append(f"| {x['repo']} | {'; '.join(x['v_chains'])} ({x['v_verdicts']}) | "
              f"{x['tofu']} ({', '.join(x['tofu_classes']) or '–'}) | {', '.join(x['tofu_same_tool']) or '–'} |")
md += ["",
 "Reading (not verified): the ToFu-0 repos are tools that execute code / commands on purpose",
 "(" + ", ".join("`" + x["v_chains"][0].split("->")[0].strip() + "`" for x in conf if not x["tofu"]) + "); Viper's judge accepts \"user input reached",
 "execSync/spawnSync/osascript and succeeded\" as an effect. `run_process` (g0t4) and `run_python_code`",
 "(yzfly) are the same shape. " + str(sum(1 for x in conf for c in x["v_chains"] if c.split("->")[-1].strip().split("@")[0].lower() in ("none", "no static findings"))) + " chains carry no class label in Viper's output (`none`, `None@0`,",
 "`No static findings`): the verdict is sink-reached on a file-write/exec sink without a static flow.", "",
 "## Open",
 "- Hand-verify the 10 confirmed chains (dangerous-by-design vs real injection) before quoting them.",
 "- openags/paper-search-mcp: confirmed in the 09-26 PC run, NOT in this run (LLM agent variance at T=0).",
 "- 45 upstream HTTP 400s: request bodies are not cached for non-200 responses; cause unknown.",
 "- 7 failed repos: 6 server-init failures under Viper (2 also failed in 09-20), 1 timeout.", "",
 "Files: `runs.c251.jsonl` (index), `confirmed_verdicts.json`, `per_repo.json` (all 251 rows),",
 "`llm_ledger_summary.json`. Raw outputs: VM `~/toolfuzzer/eval/viper_runs/c251/<slug>/`.",
]
open(P("REPORT.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md[md.index("## Headline"):md.index("## Viper's confirmed bugs vs ToFu")]))
