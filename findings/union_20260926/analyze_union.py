#!/usr/bin/env python3
"""Consolidated bug count across all sandboxed campaigns, deduped by (repo, tool,
class), with each bug's fuzz budget. Regenerates findings/union_20260926/REPORT.md.
Run from the repo root: python3 findings/union_20260926/analyze_union.py

Sources (all committed):
  60s sandboxed   findings/corpus_sbx_20260926/runs.gpt41-corpus-sbx.jsonl  (reachable corpus)
                  findings/recover_pc_20260926/runs.gpt41-recover-pc.jsonl  (recovered dead repos)
  introspection-  findings/baselines/tofu_runs_e2_20260922.jsonl : bugs on tools that EXECUTED
   on-errored     but returned 0 success (n_exec>0, n_exec_success=0); introspection tracers
                  (e.g. SSRF dial-then-fail) fire legitimately. Excludes insecure-temp-file
                  (shared-/tmp harness artefact, removed by the private-/tmp sandbox). Ran at 60s.
  24h deep        findings/repo24_20260926/runs.repo24.jsonl + runs.repo24-b.jsonl
                  first-appearance times from stitched_timelines.*.tgz split the deep-only bugs
                  into 60s-reachable vs genuinely >60s.
"""
import json, csv, os, sys, glob, tarfile, tempfile, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "eval")); from triage_findings import classify
F = lambda *p: os.path.join(ROOT, "findings", *p)

def load(p): return [json.loads(l) for l in open(p) if l.strip()]
def cand(rows):
    s = set()
    for r in rows:
        if r.get("ok") and r.get("finding_hits"):
            c = classify(r.get("triggered_sanitizers"))
            if c: s.add((r.get("repo"), r.get("tool"), c[0]))
    return s

A = cand(load(F("corpus_sbx_20260926", "runs.gpt41-corpus-sbx.jsonl"))) | \
    cand(load(F("recover_pc_20260926", "runs.gpt41-recover-pc.jsonl")))          # 60s sandboxed
B = cand(load(F("repo24_20260926", "runs.repo24.jsonl"))) | \
    cand(load(F("repo24_20260926", "runs.repo24-b.jsonl")))                       # 24h deep
best = {}
for r in load(F("baselines", "tofu_runs_e2_20260922.jsonl")):
    if r.get("ok") and r.get("finding_hits"):
        c = classify(r.get("triggered_sanitizers"))
        if c: best.setdefault((r.get("repo"), r.get("tool"), c[0]), r)
C = {k for k, v in best.items()
     if (v.get("n_exec") or 0) > 0 and not (v.get("n_exec_success") or 0) and k[2] != "insecure-temp-file"}

# first-appearance tool-clock from the deep-run stitched timelines (for the >60s split)
first = {}
for arm in ("repo24", "repo24-b"):
    idx = {r["config"].removesuffix(".json"): r for r in load(F("repo24_20260926", f"runs.{arm}.jsonl")) if r.get("config")}
    tgz = F("repo24_20260926", f"stitched_timelines.{arm}.tgz")
    with tempfile.TemporaryDirectory() as d:
        tarfile.open(tgz).extractall(d)
        for f in glob.glob(os.path.join(d, "**", "stitched_findings.csv"), recursive=True):
            r = idx.get(os.path.basename(os.path.dirname(f)))
            if not r: continue
            for row in csv.DictReader(open(f)):
                c = classify(row["triggered_sanitizers"].split(","))
                if c:
                    k = (r["repo"], r["tool"], c[0]); t = float(row["tool_clock_s"])
                    if k not in first or t < first[k]: first[k] = t

U = A | B | C
need24 = {k for k in (B - (A | C)) if first.get(k, 9e9) > 60}   # deep-only AND first fired after 60s
reach60 = U - need24
by = collections.Counter(k[2] for k in U)
out = [
 "# Consolidated bug count — all sandboxed campaigns, deduped — 2026-09-26",
 "", "Regenerated by `analyze_union.py` from committed indices. Distinct (repo, tool, class);",
 "budget = each bug's earliest fuzz budget (first-appearance on the tool clock for the deep run).",
 "insecure-temp-file shared-/tmp artefacts excluded (private-/tmp sandbox removes them).", "",
 f"## Total: {len(U)} bugs · {len({k[0] for k in U})} repos · {len({(k[0],k[1]) for k in U})} tools",
 "", "| budget | bugs |", "|---|---|",
 f"| 60 s/tool | {len(reach60)} |",
 f"| required >60 s (24 h deep) | {len(need24)} |",
 f"| **total** | **{len(U)}** |", "",
 "By class: " + ", ".join(f"{c} {n}" for c, n in by.most_common()), "",
 "## How it is built (no double-count)",
 f"- 60 s sandboxed sweeps (reachable corpus + recovered dead repos): {len(A)} bugs.",
 f"- Introspection-observed on tools that executed but errored (09-22, 60 s; temp-file excluded): "
 f"+{len(C - A)} net-new.",
 f"- 24 h deep run: +{len(B - (A | C))} net-new ({len(B - (A | C)) - len(need24)} were 60 s-reachable, "
 f"{len(need24)} genuinely needed >60 s: first-appearance 111 s–4,202 s).",
 "",
 "Per-run detail: findings/{corpus_sbx,recover_pc,repo24}_20260926/REPORT.md.",
]
open(F("union_20260926", "REPORT.md"), "w").write("\n".join(out) + "\n")
print(f"total {len(U)} | 60s {len(reach60)} | >60s {len(need24)} | repos {len({k[0] for k in U})} | tools {len({(k[0],k[1]) for k in U})}")
print("by class:", dict(by))
