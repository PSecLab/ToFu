# Atheris instruments Python, not V8. The bridge is a generated module whose
# Nth branch stands for the Nth distinct JS coverage item, so exercising new JS
# code shows up to libFuzzer as a new Python edge.
#
# COV_SLOTS must be >= the modulo used when assigning indices below. It used to
# be 2000 branches against a `% 10000` assignment, so every JS coverage item
# past the 2000th fell through the whole chain to the same `return -1` and
# became indistinguishable from every other one.
#
# COST WARNING: fake_coverage.py is a generated if-chain of COV_SLOTS branches
# and Atheris instruments EVERY branch, once per fuzzer process. The cost is
# superlinear: 512->1.4s, 1024->4.7s, 2000->17s, 10000->465s. At 10000 a whole
# corpus config spends >120s just instrumenting and gets SIGKILLed before it
# fuzzes anything (silent all-ERR campaign, 2026-09-17). Default is therefore
# 1024 -- a coverage item past the 1024th aliases (under-reports coverage, see
# the warning at the assignment below) but never crashes. Raise TOFU_JS_COV_SLOTS
# only for a single-target run where precise JS coverage matters.
COV_SLOTS = int(os.environ.get("TOFU_JS_COV_SLOTS", "1024"))

fake_cov_path = os.path.join(os.path.dirname(__file__), "fake_coverage.py")

def _generated_slots(path):
    """Branch count of an existing generated file, or -1 if absent/unreadable."""
    try:
        with open(path) as f:
            return sum(1 for line in f if line.startswith("    if idx == "))
    except OSError:
        return -1

if _generated_slots(fake_cov_path) != COV_SLOTS:
    # Regenerate whenever the size no longer matches, otherwise a stale 2000-slot
    # file silently caps the index space again.
    with open(fake_cov_path, "w") as f:
        f.write("# Generated for Atheris coverage mapping -- DO NOT EDIT.\n")
        f.write(f"# {COV_SLOTS} slots; regenerated by js_runner when TOFU_JS_COV_SLOTS changes.\n")
        f.write("def trigger(idx):\n")
        for i in range(COV_SLOTS):
            f.write(f"    if idx == {i}: return {i}\n")
        f.write("    return -1\n")

