def _inband_error(res_data):
    """The failure a server reported INSIDE a successful response, or None.

    Two shapes, both STRUCTURED -- no guessing at prose:

    1. a top-level truthy `error`/`errors` member. mcp-server-weread answers
       every input with {'error': {'message': '没有找到cookie...'}} and no
       isError, which made a credential-blocked tool look 100% executable.

    2. an MCP content block whose text parses as JSON carrying an explicit
       `"success": false` (or its own `error`). bhouston/mcp-server-text-editor
       answers refusals with
         {"content":[{"type":"text","text":
           "{\"success\":false,\"message\":\"Path must be absolute\"}"}]}
       Measured 2026-09-10 (gpt-4.1 arm): 426 alerts on that one tool, every
       one of them the tool CORRECTLY REFUSING -- "File not found:
       /etc/passwd\u0000", "Path must be absolute", "new_str parameter is
       required" -- while check_path_traversal reported a validation bypass
       because the oracle could not see the refusal.

    Still refuses to guess: only a parsed JSON object with an explicit boolean
    false `success`, or a truthy `error`, counts. Prose containing the word
    "error" does not.
    """
    if not isinstance(res_data, dict):
        return None
    for key in ("error", "errors"):
        val = res_data.get(key)
        if val:
            return val

    for block in (res_data.get("content") or []):
        if not isinstance(block, dict) or block.get("type") != "text":
            continue
        text = block.get("text")
        if not isinstance(text, str) or "{" not in text:
            continue
        try:
            payload = json.loads(text)
        except Exception:
            continue
        if not isinstance(payload, dict):
            continue
        if payload.get("success") is False:
            return payload.get("message") or payload.get("error") or "success:false"
        for key in ("error", "errors"):
            if payload.get(key):
                return payload[key]
    return None



